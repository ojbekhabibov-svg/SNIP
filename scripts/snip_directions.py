def core_number(number: str) -> str:
    s = number.upper().replace("—", "-").replace("–", "-").replace("Ё", "Е")
    s = re.sub(r"^\s*(?:ПОСОБИЕ\s+(?:К|В\s+РАЗВИТИЕ)\s+)?(?:СНИП|СН|СП)[\s-]*", "", s)
    return s.replace(" ", "")


def classify(number: str, title: str) -> list:
    found = []
    core = core_number(number)
    for rx, codes in _NRX:
        if core and rx.search(core):
            found += [c for c in codes if c not in found]
            break  # первое (самое точное) правило по номеру
    t = title.lower().replace("ё", "е")
    # общая формула заголовков части III не говорит о теме — убираем перед поиском по названию
    t = re.sub(r"правила (?:производства и приемки|организации и производства|производства) работ\.?", " ", t)
    found += [c for c in CODES if c in _RX and c not in found and _RX[c].search(t)]
    if not found:
        found = next((c for rx, c in _FRX if core and rx.search(core)), [])
    return found or ["PROCH"]
